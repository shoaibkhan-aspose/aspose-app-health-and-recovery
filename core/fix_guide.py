GUIDE: dict[str, dict] = {
    key: {"area": area, "name": name, "means": means, "impact": impact, "fix": fix, "verify": verify}
    for key, area, name, means, impact, fix, verify in _ROWS
}
AREAS = list(dict.fromkeys(row[1] for row in _ROWS))


def guide_key(check: str | None, source: str | None) -> str | None:
    """The guide row for a finding's check; discovery's 'redirected' is about the sitemap file itself."""
    if not check:
        return None
    if check == "redirected" and source == "discovery":
        return "sitemap_redirected"
    return check if check in GUIDE else None
